/** App language: hinglish (default) | hindi | english | bengali */
val LocalLang = compositionLocalOf { "hinglish" }

val LANGS = listOf("hinglish" to "Hinglish", "hindi" to "हिन्दी", "english" to "English", "bengali" to "বাংলা")

@Composable
fun T(s: String): String {
    val l = LocalLang.current
    if (l == "hinglish") return s
    return TR[l]?.get(s) ?: s
}

/** Non-composable lookup for toasts/notifications. */
fun trNow(s: String): String {
    val l = try { LdApp.settings.value.lang } catch (e: Exception) { "hinglish" }
    if (l == "hinglish") return s
    return TR[l]?.get(s) ?: s
}

